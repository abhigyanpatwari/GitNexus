export function generateFiles(opts: CiSetupOptions, detect: DetectResult): GeneratedFile[] {
  const files: GeneratedFile[] = [];

  if (opts.ci === 'github-actions' || opts.ci === 'both') {
    files.push({
      relativePath: '.github/workflows/gitnexus-ci.yml',
      content: buildGitHubActionsWorkflow(opts),
    });
  }

  if (opts.ci === 'azure-devops' || opts.ci === 'both') {
    files.push({
      relativePath: 'azure-pipelines-gitnexus.yml',
      content: buildAzurePipelineYaml(opts),
    });
  }

  if (opts.deploy === 'docker' || opts.deploy === 'both') {
    files.push({
      relativePath: 'docker-compose.gitnexus.yml',
      content: buildDockerCompose(opts),
    });
    if (opts.auth === 'token') {
      files.push({
        relativePath: 'Caddyfile',
        content: buildCaddyfile(opts),
      });
    }
  }

  if (opts.deploy === 'azure-container-app' || opts.deploy === 'both') {
    files.push({
      relativePath: 'gitnexus-aca-deploy.sh',
      content: buildAcaDeployScript(opts),
    });
  }

  files.push({
    relativePath: '.claude/gitnexus-mcp-snippet.json',
    content: buildMcpSnippet(opts),
  });

  files.push({
    relativePath: 'GITNEXUS.md',
    content: buildGitnexusMd(opts, detect),
  });

  return files;
}
