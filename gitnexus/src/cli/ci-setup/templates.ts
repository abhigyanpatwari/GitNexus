import type { CiSetupOptions, DetectResult, GeneratedFile } from './types.js';

const LICENSE_NOTICE = '# License: PolyForm-Noncommercial-1.0.0 — confirm non-commercial use';
const COMMERCIAL_NOTICE =
  '# ⚠ COMMERCIAL USE: verify PolyForm-Noncommercial-1.0.0 license before deploying to client environments.';
const GENERATED_NOTICE = '# Generated by: gitnexus ci-setup';

// The port gitnexus serve always binds inside the container/image (the host or
// proxy-facing port is derived from opts.port). Keep these in one place so the
// port contract can't drift across the generated artifacts.
const CONTAINER_PORT = 4747;
const GITNEXUS_IMAGE = 'ghcr.io/abhigyanpatwari/gitnexus:latest';

/** The Caddy reverse-proxy port (one above the gitnexus serve port). */
function caddyProxyPort(opts: CiSetupOptions): number {
  return opts.port + 1;
}

function buildGitHubActionsWorkflow(opts: CiSetupOptions): string {
  const onBlock =
    opts.branchStrategy === 'pr-scoped'
      ? `on:
  push:
    branches: [main]
  pull_request:
    types: [opened, synchronize, reopened]`
      : `on:
  push:
    branches: [main]`;

  return `${LICENSE_NOTICE}
${GENERATED_NOTICE}

name: GitNexus Index

${onBlock}

permissions:
  contents: read

concurrency:
  group: gitnexus-$\{{ github.ref }}
  cancel-in-progress: true

jobs:
  gitnexus-index:
    name: Index repository
    runs-on: ubuntu-latest
    timeout-minutes: 15

    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - uses: actions/setup-node@v4
        with:
          node-version: '22'

      - name: Analyze repository
        run: npx gitnexus@${opts.version} analyze --skills

      - name: Upload index artifact
        uses: actions/upload-artifact@v4
        with:
          name: gitnexus-index-\${{ github.sha }}
          path: .gitnexus/
          retention-days: 30

      - name: Verify index was produced
        run: |
          if [ -f .gitnexus/meta.json ]; then
            echo "✓ GitNexus index updated at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
          else
            echo "✗ GitNexus index not found" && exit 1
          fi
`;
}

function buildAzurePipelineYaml(opts: CiSetupOptions): string {
  const trigger =
    opts.branchStrategy === 'pr-scoped'
      ? `trigger:
  branches:
    include:
      - main

pr:
  branches:
    include:
      - '*'`
      : `trigger:
  branches:
    include:
      - main

pr: none`;

  return `${COMMERCIAL_NOTICE}
${GENERATED_NOTICE}

${trigger}

pool:
  vmImage: ubuntu-latest

steps:
  - checkout: self
    fetchDepth: 0

  - task: NodeTool@0
    inputs:
      versionSpec: '22.x'
    displayName: 'Set up Node.js 22'

  - script: npx gitnexus@${opts.version} analyze --skills
    displayName: 'Analyze repository'

  - task: PublishPipelineArtifact@1
    inputs:
      targetPath: '.gitnexus'
      artifact: 'gitnexus-index'
      publishLocation: 'pipeline'
    displayName: 'Upload index artifact'

  - script: |
      if [ -f .gitnexus/meta.json ]; then
        echo "✓ GitNexus index updated"
      else
        echo "✗ GitNexus index not found" && exit 1
      fi
    displayName: 'Verify index was produced'
`;
}

function buildDockerComposeTokenAuth(opts: CiSetupOptions): string {
  return `${LICENSE_NOTICE}
${GENERATED_NOTICE}
#
# Auth model: Caddy reverse proxy enforces GITNEXUS_TOKEN.
# The gitnexus service is NOT published — only the proxy port is reachable.
#
# Required environment variables (create a .env file or set in your shell):
#   GITNEXUS_TOKEN=<your-secret-token>
#   WORKSPACE_DIR=<path-to-repos>  (default: ./workspace)

services:
  gitnexus:
    image: ${GITNEXUS_IMAGE}
    # No ports: — gitnexus is accessible only to the proxy on the internal network.
    volumes:
      - gitnexus-data:/data/gitnexus
      - \${WORKSPACE_DIR:-./workspace}:/workspace:ro
    environment:
      GITNEXUS_HOME: /data/gitnexus
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:${CONTAINER_PORT}/api/health"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 15s

  gitnexus-proxy:
    image: caddy:alpine
    ports:
      - "\${GITNEXUS_PROXY_PORT:-${caddyProxyPort(opts)}}:${caddyProxyPort(opts)}"
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
    environment:
      GITNEXUS_TOKEN: \${GITNEXUS_TOKEN:?GITNEXUS_TOKEN is required}
    depends_on:
      gitnexus:
        condition: service_healthy
    restart: unless-stopped

volumes:
  gitnexus-data:
`;
}

